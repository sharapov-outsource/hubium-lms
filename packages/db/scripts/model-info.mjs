// Writes src/generated/model-info.ts from prisma/schema: for each model, its primary key,
// whether its id is a uuid(7) Prisma makes, the fields that default to now() or are
// @updatedAt, and its relations. Prisma 7's own description of the models has no defaults;
// the operation context (op-context.ts) needs them to give new rows the ids and the time of
// the operation that makes them. Runs with `prisma generate` (package.json).
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const schemaDir = path.join(root, 'prisma/schema');

function schemaFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory()
      ? schemaFiles(path.join(dir, e.name))
      : e.name.endsWith('.prisma')
        ? [path.join(dir, e.name)]
        : [],
  );
}

const text = schemaFiles(schemaDir)
  .sort()
  .map((f) => readFileSync(f, 'utf8'))
  .join('\n');

const blocks = [...text.matchAll(/^model\s+(\w+)\s*\{([\s\S]*?)^\}/gm)].map((m) => ({
  name: m[1],
  body: m[2],
}));
const models = new Set(blocks.map((b) => b.name));

const info = {};
for (const { name, body } of blocks) {
  const m = { pk: [], uuid: false, now: [], updatedAt: [], rel: {}, dataField: false };
  for (const raw of body.split('\n')) {
    const line = raw.replace(/\/\/.*$/, '').trim();
    if (!line) continue;
    const compound = /^@@id\(\[([^\]]+)\]/.exec(line);
    if (compound) m.pk = compound[1].split(',').map((s) => s.trim());
    if (line.startsWith('@@')) continue;
    const f = /^(\w+)\s+(\w+)(\[\])?(\?)?\s*(.*)$/.exec(line);
    if (!f) continue;
    const [, field, type, , , attrs] = f;
    if (field === 'data') m.dataField = true;
    if (models.has(type)) {
      m.rel[field] = type;
      continue;
    }
    if (/@id\b/.test(attrs)) {
      m.pk = [field];
      if (/@default\(uuid\(7\)\)/.test(attrs)) m.uuid = true;
    }
    if (/@default\(now\(\)\)/.test(attrs)) m.now.push(field);
    if (/@updatedAt\b/.test(attrs)) m.updatedAt.push(field);
  }
  info[name] = m;
}

const out = `// Generated by scripts/model-info.mjs from prisma/schema. Do not edit.

export interface ModelInfo {
  /** The primary key: one field, or the fields of @@id. */
  pk: string[];
  /** The id is a uuid(7) the client makes. */
  uuid: boolean;
  /** Fields that default to now(). */
  now: string[];
  /** @updatedAt fields. */
  updatedAt: string[];
  /** Relation fields and the model each points to. */
  rel: Record<string, string>;
  /** The model has a field named data (nested updates may then not be { data }). */
  dataField: boolean;
}

export const MODEL_INFO: Record<string, ModelInfo> = ${JSON.stringify(info, null, 2)};
`;
mkdirSync(path.join(root, 'src/generated'), { recursive: true });
writeFileSync(path.join(root, 'src/generated/model-info.ts'), out);
