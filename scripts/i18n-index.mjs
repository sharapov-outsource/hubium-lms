// Builds the language pack index of @hubium/i18n from the message files in the repository:
//   packages/i18n/messages/<code>.json     interface strings, with the "$language" block
//   modules/<module>/messages/<code>.json  a module's strings (namespace `mod`)
// A language exists when its core file exists. Run `pnpm i18n:index` after adding one;
// `--check` fails when the index is out of date (used by the i18n tests).
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const coreDir = path.join(root, 'packages/i18n/messages');
const outDir = path.join(root, 'packages/i18n/src/generated');
const CODE = /^[a-z]{2,3}(-[A-Z][a-zA-Z]{1,3})?$/;

const codes = readdirSync(coreDir)
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.slice(0, -5))
  .filter((c) => CODE.test(c))
  .sort();
const modules = readdirSync(path.join(root, 'modules'))
  .filter((m) => existsSync(path.join(root, 'modules', m, 'messages')))
  .sort();

const ident = (s) => s.replace(/[^a-zA-Z0-9]/g, '_');
const header =
  '// Generated by scripts/i18n-index.mjs from the message files. Do not edit:\n' +
  '// run `pnpm i18n:index` after adding or removing a language file.\n';

const locales = `${header}
export const LOCALE_CODES = ${JSON.stringify(codes)} as const;
`;

const imports = [];
const core = [];
const mods = [];
for (const c of codes) {
  imports.push(`import core_${ident(c)} from '../../messages/${c}.json' with { type: 'json' };`);
  core.push(`  ${JSON.stringify(c)}: core_${ident(c)},`);
  const own = [];
  for (const m of modules) {
    if (!existsSync(path.join(root, 'modules', m, 'messages', `${c}.json`))) continue;
    const id = `${ident(m)}_${ident(c)}`;
    imports.push(
      `import ${id} from '../../../../modules/${m}/messages/${c}.json' with { type: 'json' };`,
    );
    own.push(id);
  }
  mods.push(`  ${JSON.stringify(c)}: [${own.join(', ')}],`);
}
const packs = `${header}
${imports.join('\n')}

/** Interface strings by language code. */
export const corePacks: Record<string, Record<string, unknown>> = {
${core.join('\n')}
};

/** Module strings by language code, one object per module that has the language. */
export const modulePacks: Record<string, Record<string, unknown>[]> = {
${mods.join('\n')}
};
`;

const files = [
  [path.join(outDir, 'locales.ts'), locales],
  [path.join(outDir, 'packs.ts'), packs],
];
const stale = files.filter(([p, text]) => !existsSync(p) || readFileSync(p, 'utf8') !== text);
if (process.argv.includes('--check')) {
  if (stale.length) {
    console.error(`Language pack index is out of date: run \`pnpm i18n:index\`.`);
    process.exit(1);
  }
} else {
  for (const [p, text] of stale) writeFileSync(p, text);
  console.log(`i18n index: ${codes.join(', ')} (${modules.length} modules)`);
}
